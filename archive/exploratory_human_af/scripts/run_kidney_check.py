def cp_stats(cp_model, pmap, test_ids):
    imgs = [pmap[n] for n in test_ids]
    preds = []
    for i in range(0, len(imgs), 24):
        mb, _, _ = cp_model.eval(imgs[i:i + 24], diameter=None, channels=[0, 0], batch_size=24)
        preds.extend(mb)
    cnts = [int(p.max()) for p in preds]
    return {
        "pr_med": float(np.median(cnts)),
        "pr_mean": float(np.mean(cnts)),
        "pr_nz": int(sum(c > 0 for c in cnts)),
    }


def main():
    torch.set_num_threads(4)
    torch.set_float32_matmul_precision("high")
    torch.backends.cudnn.benchmark = True
    device = torch.device("cuda:0")

    fold = "Kidney"
    raw_dir = DEFAULT_AF_WORK / "raw"
    splits = json.loads((DEFAULT_AF_DATA / "af_lomo_splits.json").read_text(encoding="utf-8"))
    fd = load_af_fold_tensors(DEFAULT_AF_DATA, splits, fold, "raw", k_shot=20)
    gt_masks = load_gt_instance_masks(DEFAULT_AF_NPZ, fold)
    lpips_fn = build_per_image_lpips(net_type="alex", normalize=True).to(device)
    cp_model = cp_models.CellposeModel(gpu=True, model_type="nuclei")
    uni_enc = UNIEncoder(freeze=True).cuda().eval()

    results = {}

    # 1) Gather BaseFlow & UniFlow outputs already generated by run_af_human_pipeline.py
    flow_tags = [
        "Kidney__u0_base_d192__0shot",
        "Kidney__u0_base_d192__0shot_halfOD",
        "Kidney__u0_base_d192__m6_k20",
        "Kidney__u1_up64_only_d192__0shot",
        "Kidney__u1_up64_only_d192__0shot_halfOD",
        "Kidney__u1_up64_only_d192__m6_k20",
    ]
    for tag in flow_tags:
        m = json.loads((raw_dir / "eval_results" / "metrics" / f"{tag}.json").read_text(encoding="utf-8"))["metrics"]
        pmap = {n: rgb(raw_dir / "generated" / fold / tag / n) for n in fd["test_ids"]}
        nc = cp_stats(cp_model, pmap, fd["test_ids"])
        results[tag] = {**m, **nc}
        print(
            f"[KIDNEY] {tag:40s} | PSNR={m['psnr']:.2f} SSIM={m['ssim']:.4f} LPIPS={m['lpips']:.4f} "
            f"KID={m['kid']*1000:.2f} Dice={m['nuclei_dice']:.4f} Dice_ne={m['nuclei_dice_nonempty']:.4f} "
            f"| PR_nuc: med={nc['pr_med']:.1f} mean={nc['pr_mean']:.1f} nz={nc['pr_nz']}/120",
            flush=True,
        )

    # 2) UniFlow Perceptual 20-shot SRA (1*L1 + 1*grad + 2*LPIPS)
    ckpt_dir = raw_dir / "checkpoints" / fold
    codec = Codec().cuda()
    codec.load_state_dict(torch.load(ckpt_dir / "codec_rae0.08_s8800.pth", map_location="cuda", weights_only=True))
    codec.eval().requires_grad_(False)
    pre = torch.load(ckpt_dir / "Kidney__u1_up64_only_d192_pretrain.pth", map_location="cpu", weights_only=False)
    organ_pools = [
        (fd["src_pi"][[i for i, g in enumerate(fd["src_groups"]) if g == o]].cuda(),
         fd["src_he"][[i for i, g in enumerate(fd["src_groups"]) if g == o]].cuda())
        for o in sorted(set(fd["src_groups"]))
    ]
    fl_p, co_p = adapt_perceptual_af(
        "raw_Kidney_u1_perc", build_flow_model("u1_up64_only", dim=192), pre["swad"], codec,
        pre["center"], pre["scale"], organ_pools, fd["adapt_pi_t"], fd["adapt_he_t"],
        lpips_fn, uni_enc, w_l1=1.0, w_grad=1.0, w_lpips=2.0, steps=1500,
    )
    tag_perc = "Kidney__u1_up64_only_d192__m6_k20_perc"
    pmap_perc = infer_to_pngs(fl_p, co_p, fd["test_pi_t"], uni_enc, pre["center"], pre["scale"], fd["test_ids"], raw_dir / "generated" / fold / tag_perc, steps=4)
    m_perc = evaluate_split(fd["test_ids"], pmap_perc, fd["pi_rgb_map"], fd["gt_rgb_map"], gt_masks, cp_model, lpips_fn, device)
    nc_perc = cp_stats(cp_model, pmap_perc, fd["test_ids"])
    results[tag_perc] = {**m_perc, **nc_perc}
    print(
        f"[KIDNEY] {tag_perc:40s} | PSNR={m_perc['psnr']:.2f} SSIM={m_perc['ssim']:.4f} LPIPS={m_perc['lpips']:.4f} "
        f"KID={m_perc['kid']*1000:.2f} Dice={m_perc['nuclei_dice']:.4f} Dice_ne={m_perc['nuclei_dice_nonempty']:.4f} "
        f"| PR_nuc: med={nc_perc['pr_med']:.1f} mean={nc_perc['pr_mean']:.1f} nz={nc_perc['pr_nz']}/120",
        flush=True,
    )
    del fl_p, co_p, codec
    torch.cuda.empty_cache()

    # 3) Official Pix2Pix (unet_256 + 70x70 PatchGAN)
    p2p_ckpt = ckpt_dir / "pix2pix_tmp"
    p2p_ckpt.mkdir(parents=True, exist_ok=True)
    best_g0, info_p2p = train_p2p_or_cyclegan_pretrain(
        "pix2pix", fold, fd["src_pi"], fd["src_he"], fd["val_pi"], fd["val_he"],
        lpips_fn, p2p_ckpt, max_epochs=80, batch_size=8, lr=2e-4, eval_every=5, patience=6, seed=2026,
    )
    opt0 = _make_p2p_opt("pix2pix", is_train=False, checkpoints_dir=p2p_ckpt, name="infer", max_epochs=2, lr=2e-4)
    m0 = Pix2PixModel(opt0)
    m0.netG.load_state_dict(best_g0)
    m0.netG.cuda().eval()
    pmap_p0 = infer_queue2_to_pngs(_make_predict_fn("pix2pix", m0.netG), fd["test_pi_t"], fd["test_ids"], raw_dir / "generated" / fold / "Kidney__pix2pix__0shot")
    m_p0 = evaluate_split(fd["test_ids"], pmap_p0, fd["pi_rgb_map"], fd["gt_rgb_map"], gt_masks, cp_model, lpips_fn, device)
    nc_p0 = cp_stats(cp_model, pmap_p0, fd["test_ids"])
    results["Kidney__pix2pix__0shot"] = {**m_p0, **nc_p0, "best_ep": info_p2p["best_epoch"]}
    print(
        f"[KIDNEY] {'Kidney__pix2pix__0shot':40s} | PSNR={m_p0['psnr']:.2f} SSIM={m_p0['ssim']:.4f} LPIPS={m_p0['lpips']:.4f} "
        f"KID={m_p0['kid']*1000:.2f} Dice={m_p0['nuclei_dice']:.4f} Dice_ne={m_p0['nuclei_dice_nonempty']:.4f} "
        f"| PR_nuc: med={nc_p0['pr_med']:.1f} mean={nc_p0['pr_mean']:.1f} nz={nc_p0['pr_nz']}/120",
        flush=True,
    )

    # Pix2Pix 0shot + halfOD
    refs_p0 = infer_queue2_to_pngs(_make_predict_fn("pix2pix", m0.netG), fd["refs_pi_t"], fd["refs_ids"], raw_dir / "generated" / fold / "_tmp_p2p_refs")
    sc_p2p = fd["refs_od"] / mean_od([refs_p0[n] for n in fd["refs_ids"]], "p2p_refs")
    od_dir_p2p = raw_dir / "generated" / fold / "Kidney__pix2pix__0shot_halfOD"
    od_dir_p2p.mkdir(parents=True, exist_ok=True)
    pmap_pod = {}
    for nm in fd["test_ids"]:
        im = np.rint((pmap_p0[nm].astype(np.float32) + apply_od_scale(pmap_p0[nm], sc_p2p).astype(np.float32)) / 2.0).clip(0, 255).astype(np.uint8)
        pmap_pod[nm] = im
        Image.fromarray(im).save(od_dir_p2p / nm)
    m_pod = evaluate_split(fd["test_ids"], pmap_pod, fd["pi_rgb_map"], fd["gt_rgb_map"], gt_masks, cp_model, lpips_fn, device)
    nc_pod = cp_stats(cp_model, pmap_pod, fd["test_ids"])
    results["Kidney__pix2pix__0shot_halfOD"] = {**m_pod, **nc_pod}
    print(
        f"[KIDNEY] {'Kidney__pix2pix__0shot_halfOD':40s} | PSNR={m_pod['psnr']:.2f} SSIM={m_pod['ssim']:.4f} LPIPS={m_pod['lpips']:.4f} "
        f"KID={m_pod['kid']*1000:.2f} Dice={m_pod['nuclei_dice']:.4f} Dice_ne={m_pod['nuclei_dice_nonempty']:.4f} "
        f"| PR_nuc: med={nc_pod['pr_med']:.1f} mean={nc_pod['pr_mean']:.1f} nz={nc_pod['pr_nz']}/120",
        flush=True,
    )
    del m0
    torch.cuda.empty_cache()

    # Pix2Pix 20-shot
    g20_state, _ = adapt_p2p_or_cyclegan_k20(
        "pix2pix", fold, info_p2p["full_model_state"], fd["adapt_pi_t"], fd["adapt_he_t"],
        p2p_ckpt, adapt_steps=300, batch_size=8, base_lr=2e-4, seed=7202,
    )
    opt20 = _make_p2p_opt("pix2pix", is_train=False, checkpoints_dir=p2p_ckpt, name="infer20", max_epochs=2, lr=2e-4)
    m20 = Pix2PixModel(opt20)
    m20.netG.load_state_dict(g20_state)
    m20.netG.cuda().eval()
    pmap_p20 = infer_queue2_to_pngs(_make_predict_fn("pix2pix", m20.netG), fd["test_pi_t"], fd["test_ids"], raw_dir / "generated" / fold / "Kidney__pix2pix__20shot")
    m_p20 = evaluate_split(fd["test_ids"], pmap_p20, fd["pi_rgb_map"], fd["gt_rgb_map"], gt_masks, cp_model, lpips_fn, device)
    nc_p20 = cp_stats(cp_model, pmap_p20, fd["test_ids"])
    results["Kidney__pix2pix__20shot"] = {**m_p20, **nc_p20}
    print(
        f"[KIDNEY] {'Kidney__pix2pix__20shot':40s} | PSNR={m_p20['psnr']:.2f} SSIM={m_p20['ssim']:.4f} LPIPS={m_p20['lpips']:.4f} "
        f"KID={m_p20['kid']*1000:.2f} Dice={m_p20['nuclei_dice']:.4f} Dice_ne={m_p20['nuclei_dice_nonempty']:.4f} "
        f"| PR_nuc: med={nc_p20['pr_med']:.1f} mean={nc_p20['pr_mean']:.1f} nz={nc_p20['pr_nz']}/120",
        flush=True,
    )

    # Visual strip (4 Kidney samples spanning glomerulus/tubules)
    picks = [fd["test_ids"][i] for i in [0, 20, 60, 100]]
    cols = [
        ("AF (raw)", fd["pi_rgb_map"]),
        ("GT H&E", fd["gt_rgb_map"]),
        ("Pix2Pix 20shot", pmap_p20),
        ("BaseFlow 20shot", {n: rgb(raw_dir / "generated" / fold / "Kidney__u0_base_d192__m6_k20" / n) for n in picks}),
        ("UniFlow SRA 20shot", {n: rgb(raw_dir / "generated" / fold / "Kidney__u1_up64_only_d192__m6_k20" / n) for n in picks}),
        ("UniFlow perc 20shot", pmap_perc),
    ]
    W, H, pad, header = 256, 256, 4, 28
    canvas = Image.new("RGB", (len(cols) * (W + pad), header + len(picks) * (H + pad)), (255, 255, 255))
    draw = ImageDraw.Draw(canvas)
    for ci, (t, _) in enumerate(cols):
        draw.text((ci * (W + pad) + 6, 6), t, fill=(0, 0, 0))
    for ri, nm in enumerate(picks):
        for ci, (_, mp) in enumerate(cols):
            canvas.paste(Image.fromarray(mp[nm]), (ci * (W + pad), header + ri * (H + pad)))
    vis_p = Path(r"C:\Users\felix\.gemini\antigravity\brain\787d0ac0-8ece-45d1-9c24-ccf762231692\scratch\af_kidney_check_vis.png")
    canvas.save(vis_p)

    out_json = Path(r"C:\Users\felix\.gemini\antigravity\brain\787d0ac0-8ece-45d1-9c24-ccf762231692\scratch\kidney_check_results.json")
    out_json.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"[DONE] Saved {out_json} & {vis_p}", flush=True)


if __name__ == "__main__":
    main()
